// The "Vendored skills" section of NOTICE is generated from vendor.json, so
// the credit for each copied skill cannot drift from the manifest.
export const HEADING = 'Vendored skills';

export function renderNotice(current, manifest) {
  const at = current.indexOf(`${HEADING}\n`);
  const head = (at === -1 ? current : current.slice(0, at)).trimEnd();
  const names = Object.keys(manifest.skills).sort();
  const lines = names.length
    ? names.map((name) => {
        const e = manifest.skills[name];
        const state = e.modified ? 'modified copy' : 'unmodified copy';
        return `- ${name}: ${state} of https://github.com/${e.source}/tree/${e.commit}/${e.path}\n  (${e.license}; licence text in skills/${name}/)`;
      })
    : ['(none yet)'];
  return `${head}\n\n${HEADING}\n${'-'.repeat(HEADING.length)}\nGenerated by scripts/vendor.mjs from vendor.json. Do not edit by hand.\n\n${lines.join('\n')}\n`;
}
